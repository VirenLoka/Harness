"""The two instruments must agree about the span.

protactrain is the only package that imports both molbench and protacbench, so
it is the only place this can be asserted. It matters because the disagreement
is invisible from inside either one:

  - the policy sees molbench's `span_bonds`, because check_protac_linker is the
    tool it is told decides acceptance,
  - the reward scores protacbench's `span`, via grade.measure,
  - and protocol.score_grounding audits a span the reply quotes against
    grade.measure's number.

So while they disagreed, a policy that honestly quoted the tool reading was
charged for a FALSE claim on exactly those molecules -- the reward punishing
the behaviour it exists to encourage, with nothing anywhere raising.

Measured before the fix: 1,940 of 1,987 measurable corpus molecules agreed,
and all 47 that did not had a linker attaching at three or more atoms. Two
separate causes, both now fixed:

  1. protacbench walked `Chem.GetShortestPath` over the WHOLE molecule, which
     routes through a fragment whenever a shorter way round exists. On a
     three-attachment linker it took `anchor_atoms[0]` and `anchor_atoms[1]`
     by sorted atom index, which routinely picks two anchors on the same
     fragment and measures a path that never enters the linker.
     Fixed by structures.span_through_linker.
  2. repair.match_fragments was first-fit, so a symmetric warhead could claim
     an atom in the middle of the linker and leave the leftover in two pieces
     (`C.CCCCC` for a linker that is really `CCCCCC`). The two packages then
     measured different regions entirely. Fixed by preferring an assignment
     that leaves the linker connected.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "repair_tasks.jsonl"

pytest.importorskip("rdkit", reason="the span is measured with RDKit")


def _molbench():
    path = str(ROOT / "molbench")
    if path not in sys.path:
        sys.path.insert(0, path)
    try:
        import server  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        pytest.skip(f"molbench is not importable here: {exc}")
    return server


def _rows(limit: int):
    if not CORPUS.exists():
        pytest.skip(
            "repair_tasks.jsonl is gitignored and absent; it is regenerated by "
            "`python -m protacbench assess` on the host that ran the sampling"
        )
    out = []
    with CORPUS.open() as handle:
        for line in handle:
            row = json.loads(line)
            frags = row.get("fragment_smiles") or []
            if row.get("protac_smiles") and len(frags) == 2 and all(frags):
                out.append(row)
            if len(out) >= limit:
                break
    return out


def _both(row) -> tuple[int | None, int | None] | None:
    """(protacbench span, molbench span) or None when not measurable."""
    from rdkit import Chem, rdBase

    from protacbench.repair import match_fragments
    from protacbench.structures import linker_view

    server = _molbench()
    smiles, frags = row["protac_smiles"], row["fragment_smiles"]

    with rdBase.BlockLogs():
        mol = Chem.MolFromSmiles(smiles)
    if mol is None or len(Chem.GetMolFrags(mol)) > 1:
        return None
    matches = match_fragments(mol, frags)
    if matches is None:
        return None
    claimed = {i for m in matches for i in m}
    linker = [i for i in range(mol.GetNumAtoms()) if i not in claimed]
    if not linker:
        return None

    view = linker_view(mol, linker)
    tool = server.check_protac_linker(smiles, frags[0], frags[1])
    return view.path_length_bonds, tool.get("span_bonds")


def test_the_two_instruments_agree_about_the_span_across_the_corpus():
    rows = _rows(400)
    disagreements = []
    measured = 0
    for row in rows:
        pair = _both(row)
        if pair is None:
            continue
        measured += 1
        if pair[0] != pair[1]:
            disagreements.append((row["task_id"], pair[0], pair[1]))

    assert measured > 100, f"only {measured} molecules were measurable; corpus changed?"
    assert not disagreements, (
        f"{len(disagreements)} of {measured} molecules disagree about the span. "
        "A policy quoting the tool reading would be charged for a false claim "
        f"on these. First few: {disagreements[:5]}"
    )


def test_the_two_packages_isolate_the_same_linker():
    """The span can only agree if both are measuring the same atoms."""
    from rdkit import Chem, rdBase

    from protacbench.repair import match_fragments
    from protacbench.structures import linker_view

    server = _molbench()
    mismatched = []
    checked = 0
    for row in _rows(200):
        smiles, frags = row["protac_smiles"], row["fragment_smiles"]
        with rdBase.BlockLogs():
            mol = Chem.MolFromSmiles(smiles)
        if mol is None or len(Chem.GetMolFrags(mol)) > 1:
            continue
        matches = match_fragments(mol, frags)
        if matches is None:
            continue
        claimed = {i for m in matches for i in m}
        linker = [i for i in range(mol.GetNumAtoms()) if i not in claimed]
        if not linker:
            continue
        checked += 1
        ours = linker_view(mol, linker).smiles
        theirs = server.check_protac_linker(smiles, frags[0], frags[1]).get(
            "linker_smiles"
        )
        if ours != theirs:
            mismatched.append((row["task_id"], ours, theirs))

    assert checked > 50
    assert not mismatched, (
        f"{len(mismatched)} of {checked} molecules resolve to different linker "
        f"regions in the two packages. First few: {mismatched[:5]}"
    )


def test_match_fragments_prefers_an_assignment_leaving_a_connected_linker():
    """The root cause of the residual disagreement, pinned directly.

    635-0 is the corpus molecule that exposed it: first-fit claimed an atom in
    the middle of a hexyl linker and reported it as `C.CCCCC`.
    """
    from rdkit import Chem, rdBase

    from protacbench.repair import match_fragments

    rows = {r["task_id"]: r for r in _rows(2229)}
    row = rows.get("635-0-generated")
    if row is None:
        pytest.skip("635-0-generated is not in this corpus")

    with rdBase.BlockLogs():
        mol = Chem.MolFromSmiles(row["protac_smiles"])
    matches = match_fragments(mol, row["fragment_smiles"])
    assert matches is not None

    claimed = {i for m in matches for i in m}
    editable = Chem.RWMol(mol)
    for index in sorted(claimed, reverse=True):
        editable.RemoveAtom(index)
    pieces = Chem.GetMolFrags(editable.GetMol())
    assert len(pieces) == 1, (
        "the leftover linker came back in "
        f"{len(pieces)} pieces; first-fit claimed a linker atom again"
    )


def test_span_through_linker_refuses_a_linker_that_does_not_bridge():
    """One side means it dangles. The honest answer is None, not a number."""
    from rdkit import Chem

    from protacbench.structures import span_through_linker

    # Toluene: treat the methyl as the "linker". It attaches to one side only.
    mol = Chem.MolFromSmiles("Cc1ccccc1")
    methyl = [0]
    anchors = [1]
    span, pair = span_through_linker(mol, methyl, anchors)
    assert span is None and pair is None


def test_span_through_linker_counts_both_crossing_bonds():
    """A three-atom bridge between two rings spans four bonds, not two."""
    from rdkit import Chem

    from protacbench.structures import span_through_linker

    mol = Chem.MolFromSmiles("c1ccccc1CCCc1ccccc1")
    linker = [6, 7, 8]
    anchors = [5, 9]
    span, pair = span_through_linker(mol, linker, anchors)
    # two bonds inside the linker, plus one crossing at each end
    assert span == 4
    assert pair is not None and set(pair) == {5, 9}
